#!/usr/bin/env bash
set -euo pipefail
base="5maNcI4__U10_de5L13_Mn4U0u4trfn_"
# indices from recipe.asm (lines 190..285)
hex_indices=(
  0x14 0x19 0x1e 0x23 0x17 0x1a 0x1d 0x20
  0x18 0x15 0x16 0x1b 0x1c 0x21 0x22 0x1f
  0x24 0x29 0x2e 0x33 0x27 0x2a 0x2d 0x30
  0x28 0x25 0x26 0x2b 0x2c 0x31 0x32 0x2f
)
res=""
for h in "${hex_indices[@]}"; do
  # Convert hex to decimal and shift by 0x14
  idx=$((h-0x14))
  ch=${base:idx:1}
  res+="$ch"
done
printf "%s\n" "$res"
